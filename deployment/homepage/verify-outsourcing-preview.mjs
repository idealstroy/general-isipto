import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
const backup='_backups/outsourcing-before-preview-2026-10-26T07-33-03-853Z';
const hash=x=>crypto.createHash('sha256').update(x).digest('hex');
const manifest=JSON.parse(fs.readFileSync(backup+'/manifest.json'));
assert.equal(hash(fs.readFileSync(manifest.source)),manifest.sourceSha256,'Active template changed');
const original=fs.readFileSync(manifest.source,'utf8');
const preview=fs.readFileSync('modx-isipto/_preview/outsourcing-pto/template.html','utf8');
const hrefs=s=>[...s.matchAll(/\bhref="([^"]+)"/g)].map(x=>x[1]);
assert.deepEqual(hrefs(original).filter(x=>!hrefs(preview).includes(x)),[],'Original links were removed');
const prices=s=>[...s.matchAll(/<div class="stoimost">([\s\S]*?)<\/div>/g)].map(x=>x[1]);
assert.deepEqual(prices(preview),prices(original),'Price table changed');
assert.equal((preview.match(/\[\[!AjaxForm\?/g)||[]).length,(original.match(/\[\[!AjaxForm\?/g)||[]).length);
assert.equal((preview.match(/&hooks=`FormItSaveForm,bitrix24_hooks`/g)||[]).length,3);
assert(!/бер[её]м на себя/i.test(preview),'Banned wording remains');
assert(!/1 - 3%|0,5-2%/.test(preview),'Old percentage pitch remains');
const before=await fetch(manifest.originalUrl).then(r=>r.text());
assert(before.includes('Аутсорсинг для заказчиков и подрядчиков “под ключ”'),'Active page no longer has the original content');
assert(!before.includes('Организуем службу ПТО на вашем объекте'),'Preview leaked into the active page');
const response=await fetch(manifest.previewUrl);
assert.equal(response.status,200);
assert.match(response.headers.get('x-robots-tag'),/noindex/);
assert.match(response.headers.get('cache-control'),/no-store/);
const html=await response.text();
const forms=[...html.matchAll(/<form\b[^>]*>[\s\S]*?<\/form>/gi)].map(x=>x[0]);
const info=forms.map(s=>({fields:[...s.matchAll(/\bname="([^"]+)"/g)].map(x=>x[1]),submit:[...s.matchAll(/type="submit"[^>]*value="([^"]+)"/g)].map(x=>x[1])}));
assert.equal(forms.length,4,'Three page forms and native popup must render');
assert.equal(info.filter(x=>x.submit.includes('Получить расчёт')).length,3,'Page form captions must be updated');
const oldForms=[...before.matchAll(/<form\b[^>]*>[\s\S]*?<\/form>/gi)].map(x=>x[0]);
const fieldNames=s=>[...s.matchAll(/\bname="([^"]+)"/g)].map(x=>x[1]);
assert.deepEqual(forms.map(fieldNames),oldForms.map(fieldNames),'Native form fields changed');
const css=s=>[...s.matchAll(/<link\b[^>]*rel="stylesheet"[^>]*>/g)].map(x=>x[0]);
assert.deepEqual(css(before),css(html),'Common stylesheet loading changed');
const h1=s=>(s.match(/<h1\b[^>]*>([\s\S]*?)<\/h1>/i)||[])[1];
assert.equal(h1(before),h1(html),'H1 changed');
const audit=spawn(process.execPath,['deployment/homepage/run-local-php.mjs','deployment/homepage/audit-outsourcing-preview.php'],{windowsHide:true});
let auditText='',auditError='';
audit.stdout.setEncoding('utf8');audit.stderr.setEncoding('utf8');
audit.stdout.on('data',x=>auditText+=x);audit.stderr.on('data',x=>auditError+=x);
assert.equal(await new Promise((resolve,reject)=>{audit.on('error',reject);audit.on('close',resolve);}),0,auditError);
assert.deepEqual(JSON.parse(auditText),JSON.parse(fs.readFileSync(backup+'/modx-fingerprints.json','utf8')),'MODX resources or shared elements changed');
const report={time:new Date().toISOString(),activeTemplateUnchanged:true,modxDatabaseUnchanged:true,allOriginalLinksPreserved:true,pricesUnchanged:true,nativeHooksPreserved:true,nativeFormFieldsPreserved:true,commonStylesheetsUnchanged:true,status:response.status,robots:response.headers.get('x-robots-tag'),cache:response.headers.get('cache-control'),forms:info,unparsedTags:(html.match(/\[\[/g)||[]).length};
fs.mkdirSync('output/playwright',{recursive:true});
fs.writeFileSync('output/playwright/outsourcing-preview-check.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
